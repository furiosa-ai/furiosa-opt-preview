/// Marshals values sent to device functions into structural NPU bindings.
///
/// # Implements DeviceSend
///
/// - Device memory types: `HbmTensor`, `HbmTensorView`, `HbmTensorViewMut`
/// - Context types: `&mut Context`
/// - Tuples of DeviceSend types (for argument composition)
///
/// # Does NOT implement DeviceSend
///
/// - `HostTensor` - lives in host memory
/// - Scalars - no NPU binding representation
/// - `Vec<T>`, `String`, etc. - general collections
///
/// User-defined structs opt in via `#[derive(DeviceSend)]`, which requires every
/// field to be `DeviceSend` (so a struct is `DeviceSend` iff all its fields are).
pub trait DeviceSend {
    /// Creates this value's NPU bindings.
    fn bind(&self) -> impl crate::__private::Bindings;
}

/// Device function trait, generated by `#[device]` macro.
///
/// `cargo <subcommand>`: `execute()` runs the original function body on CPU. `cargo furiosa-opt <subcommand>`:
/// `execute()` loads the compiled EDF and runs on NPU.
///
/// Device functions accept and return only values that can cross the device boundary.
///
/// ```compile_fail,E0277
/// use furiosa_opt_std::runtime::DeviceFn;
///
/// struct Invalid;
///
/// impl DeviceFn<i32> for Invalid {
///     type Output = ();
///
///     async fn execute(_: i32) {}
/// }
/// ```
///
/// ```compile_fail,E0277
/// use furiosa_opt_std::runtime::DeviceFn;
///
/// struct Invalid;
///
/// impl DeviceFn<()> for Invalid {
///     type Output = String;
///
///     async fn execute(_: ()) -> String {
///         String::new()
///     }
/// }
/// ```
///
/// ```compile_fail,E0277
/// use furiosa_opt_std::runtime::{DeviceFn, DeviceSend};
///
/// struct Args;
/// struct Output;
/// struct Invalid;
///
/// impl DeviceSend for Args {
///     fn bind(&self) -> impl furiosa_opt_std::__private::Bindings {
///         furiosa_opt_std::__private::empty()
///     }
/// }
///
/// impl DeviceSend for Output {
///     fn bind(&self) -> impl furiosa_opt_std::__private::Bindings {
///         furiosa_opt_std::__private::empty()
///     }
/// }
///
/// impl DeviceFn<Args> for Invalid {
///     type Output = Output;
///
///     async fn execute(_: Args) -> Output {
///         Output
///     }
/// }
/// ```
pub trait DeviceFn<Args: DeviceSend> {
    /// Return type of the device function.
    type Output: crate::__private::DeviceOutput;
    /// Execute the device function.
    fn execute(args: Args) -> impl std::future::Future<Output = Self::Output>;
    /// Execute the device function into caller-owned output bindings.
    fn execute_into(args: Args, output: &mut Self::Output) -> impl std::future::Future<Output = ()> {
        async move {
            *output = Self::execute(args).await;
        }
    }
}

/// A device-function launch that returns its allocated output when awaited.
#[must_use = "launches do nothing unless awaited"]
#[derive(Debug)]
pub struct Launch<F, Args> {
    function: F,
    args: Args,
}

impl<F, Args> Launch<F, Args>
where
    Args: DeviceSend,
    F: DeviceFn<Args>,
{
    /// Bind this launch to caller-owned output bindings.
    pub fn output(self, output: &mut F::Output) -> LaunchInto<'_, F, Args> {
        LaunchInto {
            function: self.function,
            args: self.args,
            output,
        }
    }
}

impl<F, Args> std::future::IntoFuture for Launch<F, Args>
where
    Args: DeviceSend,
    F: DeviceFn<Args>,
{
    type Output = F::Output;
    type IntoFuture = impl std::future::Future<Output = Self::Output>;

    fn into_future(self) -> Self::IntoFuture {
        async move {
            let _ = self.function;
            F::execute(self.args).await
        }
    }
}

/// A device-function launch bound to caller-owned output bindings.
#[must_use = "launches do nothing unless awaited"]
#[derive(Debug)]
pub struct LaunchInto<'output, F, Args>
where
    Args: DeviceSend,
    F: DeviceFn<Args>,
{
    function: F,
    args: Args,
    output: &'output mut F::Output,
}

impl<F, Args> std::future::IntoFuture for LaunchInto<'_, F, Args>
where
    Args: DeviceSend,
    F: DeviceFn<Args>,
{
    type Output = ();
    type IntoFuture = impl std::future::Future<Output = Self::Output>;

    fn into_future(self) -> Self::IntoFuture {
        async move {
            let _ = self.function;
            F::execute_into(self.args, self.output).await;
        }
    }
}

/// Prepares a device-function launch.
///
/// Takes `F` by value so callers can pass the snake_case const emitted by `#[device]` without
/// turbofishing the generated PascalCase unit struct. The value is only used for trait dispatch.
pub fn launch<F, Args>(function: F, args: Args) -> Launch<F, Args>
where
    Args: DeviceSend,
    F: DeviceFn<Args>,
{
    Launch { function, args }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Manual;

    struct Value(i32);

    impl DeviceSend for Value {
        fn bind(&self) -> impl crate::__private::Bindings {
            crate::__private::empty()
        }
    }

    impl crate::__private::DeviceOutput for Value {
        fn count() -> usize {
            0
        }

        fn alloc_into(_: &crate::backend::npu::Kernel, _: &mut Vec<crate::backend::npu::Binding>) {}

        fn take(_: &mut impl Iterator<Item = crate::backend::npu::Binding>) -> Self {
            Self(0)
        }
    }

    impl DeviceFn<Value> for Manual {
        type Output = Value;

        fn execute(value: Value) -> impl std::future::Future<Output = Value> {
            std::future::ready(Value(value.0 + 1))
        }
    }

    #[tokio::test]
    async fn manual_device_fn_uses_default_output() {
        let mut output = Value(0);

        launch(Manual, Value(1)).output(&mut output).await;

        assert_eq!(output.0, 2);
    }
}
